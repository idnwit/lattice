//! The runner side of reducers: [`Dispatch`] and [`AppError`] (06-apps.md, Interface).
//!
//! The host moves opaque action bytes. Only the code `#[interface]` generates knows the types:
//! it decodes an action, calls the reducer, and encodes `Res` or the error.

use serde::Serialize;
use serde::de::DeserializeOwned;

use crate::{App, Ctx};

/// Platform code: an action that does not decode as the app's action enum.
pub const BAD_ACTION: &str = "app.bad_action";
/// Platform code: a reply or an error that does not encode or decode.
pub const BAD_REPLY: &str = "app.bad_reply";
/// Code of an app error that is not an enum variant (the app broke the one-enum rule).
const NOT_A_VARIANT: &str = "app.error";

/// A refused call, as it crosses the wire: `ActionResult{error: code, detail}`.
///
/// An app error has the serde variant name of the app's error as `code` and its postcard
/// encoding as `detail`, never empty (a postcard enum is at least its tag). A platform error
/// (`app.bad_action`, `worker.no_instance`, …) has an empty `detail`: that is how a client
/// tells them apart.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error, serde::Serialize, serde::Deserialize)]
#[error("{code}")]
pub struct AppError {
    code: String,
    detail: Vec<u8>,
}

impl AppError {
    /// A platform error: a stable code, no detail.
    pub fn platform(code: &str) -> Self {
        Self {
            code: code.to_owned(),
            detail: Vec::new(),
        }
    }

    /// An app error: the variant name of `error` and its encoding.
    pub fn of<E: Serialize>(error: &E) -> Self {
        match lattice_state::encode(error) {
            Ok(detail) if !detail.is_empty() => Self {
                code: variant_name(error).unwrap_or(NOT_A_VARIANT).to_owned(),
                detail,
            },
            // A unit struct encodes to nothing; it cannot be told from a platform error.
            Ok(_) | Err(_) => Self::platform(BAD_REPLY),
        }
    }

    /// Rebuilds an error read from the wire.
    pub fn from_wire(code: String, detail: Vec<u8>) -> Self {
        Self { code, detail }
    }

    /// The stable code: the app error's variant name, or a namespaced platform code.
    pub fn code(&self) -> &str {
        &self.code
    }

    /// The postcard-encoded app error; empty for a platform error.
    pub fn detail(&self) -> &[u8] {
        &self.detail
    }

    /// True for a platform error (empty `detail`).
    pub fn is_platform(&self) -> bool {
        self.detail.is_empty()
    }

    /// `(code, detail)`, to put on the wire.
    pub fn into_parts(self) -> (String, Vec<u8>) {
        (self.code, self.detail)
    }
}

/// The runner adapter of an interface trait. `#[interface]` implements it for
/// `XApiRunner<T>`; the host registers that type (`hosted::<TerminalApiRunner<Terminal>>`).
pub trait Dispatch {
    /// The app whose reducers this dispatches to.
    type App: App;

    /// Decodes `action`, calls the reducer, and encodes its `Res`.
    ///
    /// # Errors
    ///
    /// The reducer's error as an [`AppError`], or [`BAD_ACTION`] when `action` does not decode.
    /// The host rolls the draft back on any error.
    fn dispatch(
        app: &mut Self::App,
        ctx: &mut Ctx,
        state: &mut <Self::App as App>::State,
        action: &[u8],
    ) -> Result<Vec<u8>, AppError>;
}

/// The serde variant name of an enum value: what a `Serializer` sees as `variant`.
///
/// `None` for a value that is not an enum variant. Honors `#[serde(rename_all = …)]`, so
/// `#[serde(rename_all = "snake_case")]` gives snake-case wire codes.
pub fn variant_name<T: Serialize + ?Sized>(value: &T) -> Option<&'static str> {
    value.serialize(variant::VariantName).ok()
}

/// Helpers for code generated by `#[interface]`. Not part of the API.
#[doc(hidden)]
pub mod __private {
    pub use serde;

    use super::{AppError, BAD_ACTION, BAD_REPLY, DeserializeOwned, Serialize};
    use crate::call::{Caller, RawCallError, RawTicket, Ticket};

    /// Decodes an action enum, or refuses with [`BAD_ACTION`].
    ///
    /// # Errors
    ///
    /// [`BAD_ACTION`] when the bytes are not one whole action.
    pub fn decode_action<A: DeserializeOwned>(bytes: &[u8]) -> Result<A, AppError> {
        lattice_state::decode(bytes).map_err(|_| AppError::platform(BAD_ACTION))
    }

    /// Encodes a reducer's outcome. `E` is the app's `App::Error`, so a reducer with another
    /// error type does not compile.
    ///
    /// # Errors
    ///
    /// The app error, or [`BAD_REPLY`] when `Res` does not encode.
    pub fn reply<R: Serialize, E: Serialize>(res: Result<R, E>) -> Result<Vec<u8>, AppError> {
        match res {
            Ok(r) => lattice_state::encode(&r).map_err(|_| AppError::platform(BAD_REPLY)),
            Err(e) => Err(AppError::of(&e)),
        }
    }

    /// Encodes an action and sends it through `caller`.
    pub fn call<C: Caller + ?Sized, A: Serialize, R, E>(caller: &C, action: &A) -> Ticket<R, E> {
        let raw = match lattice_state::encode(action) {
            Ok(bytes) => caller.call(bytes),
            Err(_) => RawTicket::ready(Err(RawCallError::Refused(AppError::platform(BAD_ACTION)))),
        };
        Ticket::new(raw)
    }
}

/// A `Serializer` that only answers "which enum variant is this?".
mod variant {
    use serde::ser::{self, Impossible, Serialize, Serializer};

    /// Not an enum variant.
    #[derive(Debug)]
    pub(super) struct NotVariant;

    impl std::fmt::Display for NotVariant {
        fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
            f.write_str("not an enum variant")
        }
    }

    impl std::error::Error for NotVariant {}

    impl ser::Error for NotVariant {
        fn custom<T: std::fmt::Display>(_msg: T) -> Self {
            Self
        }
    }

    /// Captures the variant name; every other shape is [`NotVariant`].
    pub(super) struct VariantName;

    /// A tuple or struct variant: fields are skipped, the name is kept.
    pub(super) struct Fields(&'static str);

    impl ser::SerializeTupleVariant for Fields {
        type Ok = &'static str;
        type Error = NotVariant;
        fn serialize_field<T: Serialize + ?Sized>(&mut self, _: &T) -> Result<(), NotVariant> {
            Ok(())
        }
        fn end(self) -> Result<&'static str, NotVariant> {
            Ok(self.0)
        }
    }

    impl ser::SerializeStructVariant for Fields {
        type Ok = &'static str;
        type Error = NotVariant;
        fn serialize_field<T: Serialize + ?Sized>(
            &mut self,
            _: &'static str,
            _: &T,
        ) -> Result<(), NotVariant> {
            Ok(())
        }
        fn end(self) -> Result<&'static str, NotVariant> {
            Ok(self.0)
        }
    }

    /// Generates the methods that refuse a non-enum shape.
    macro_rules! refuse {
        ($($name:ident($($arg:ty),*);)*) => {
            $(fn $name(self, $(_: $arg),*) -> Result<&'static str, NotVariant> { Err(NotVariant) })*
        };
    }

    impl Serializer for VariantName {
        type Ok = &'static str;
        type Error = NotVariant;
        type SerializeSeq = Impossible<&'static str, NotVariant>;
        type SerializeTuple = Impossible<&'static str, NotVariant>;
        type SerializeTupleStruct = Impossible<&'static str, NotVariant>;
        type SerializeTupleVariant = Fields;
        type SerializeMap = Impossible<&'static str, NotVariant>;
        type SerializeStruct = Impossible<&'static str, NotVariant>;
        type SerializeStructVariant = Fields;

        refuse! {
            serialize_bool(bool); serialize_i8(i8); serialize_i16(i16); serialize_i32(i32);
            serialize_i64(i64); serialize_u8(u8); serialize_u16(u16); serialize_u32(u32);
            serialize_u64(u64); serialize_f32(f32); serialize_f64(f64); serialize_char(char);
            serialize_str(&str); serialize_bytes(&[u8]); serialize_none(); serialize_unit();
            serialize_unit_struct(&'static str);
        }

        fn serialize_some<T: Serialize + ?Sized>(self, _: &T) -> Result<&'static str, NotVariant> {
            Err(NotVariant)
        }

        fn serialize_unit_variant(
            self,
            _: &'static str,
            _: u32,
            variant: &'static str,
        ) -> Result<&'static str, NotVariant> {
            Ok(variant)
        }

        fn serialize_newtype_struct<T: Serialize + ?Sized>(
            self,
            _: &'static str,
            value: &T,
        ) -> Result<&'static str, NotVariant> {
            value.serialize(self)
        }

        fn serialize_newtype_variant<T: Serialize + ?Sized>(
            self,
            _: &'static str,
            _: u32,
            variant: &'static str,
            _: &T,
        ) -> Result<&'static str, NotVariant> {
            Ok(variant)
        }

        fn serialize_seq(self, _: Option<usize>) -> Result<Self::SerializeSeq, NotVariant> {
            Err(NotVariant)
        }

        fn serialize_tuple(self, _: usize) -> Result<Self::SerializeTuple, NotVariant> {
            Err(NotVariant)
        }

        fn serialize_tuple_struct(
            self,
            _: &'static str,
            _: usize,
        ) -> Result<Self::SerializeTupleStruct, NotVariant> {
            Err(NotVariant)
        }

        fn serialize_tuple_variant(
            self,
            _: &'static str,
            _: u32,
            variant: &'static str,
            _: usize,
        ) -> Result<Fields, NotVariant> {
            Ok(Fields(variant))
        }

        fn serialize_map(self, _: Option<usize>) -> Result<Self::SerializeMap, NotVariant> {
            Err(NotVariant)
        }

        fn serialize_struct(
            self,
            _: &'static str,
            _: usize,
        ) -> Result<Self::SerializeStruct, NotVariant> {
            Err(NotVariant)
        }

        fn serialize_struct_variant(
            self,
            _: &'static str,
            _: u32,
            variant: &'static str,
            _: usize,
        ) -> Result<Fields, NotVariant> {
            Ok(Fields(variant))
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde::Deserialize;

    #[derive(Debug, PartialEq, Serialize, Deserialize)]
    #[serde(rename_all = "snake_case")]
    enum Oops {
        NoShell,
        TooBig(u32),
        BadSize { cols: u16, rows: u16 },
        Pair(u8, u8),
    }

    #[test]
    fn variant_names_follow_serde_renames() {
        let cases = [
            (Oops::NoShell, "no_shell"),
            (Oops::TooBig(7), "too_big"),
            (Oops::BadSize { cols: 0, rows: 1 }, "bad_size"),
            (Oops::Pair(1, 2), "pair"),
        ];
        for (value, want) in cases {
            assert_eq!(variant_name(&value), Some(want), "case={want}");
        }
        assert_eq!(variant_name(&7u8), None);
        assert_eq!(variant_name(&"text"), None);
    }

    #[test]
    fn app_error_carries_the_variant_and_its_encoding() {
        let e = AppError::of(&Oops::TooBig(3));
        assert_eq!(e.code(), "too_big");
        assert!(!e.is_platform());
        let back: Oops = lattice_state::decode(e.detail()).unwrap();
        assert_eq!(back, Oops::TooBig(3));
        assert!(AppError::platform(BAD_ACTION).is_platform());
    }

    #[test]
    fn reply_encodes_the_result_or_the_error() {
        let ok: Result<u16, Oops> = Ok(5);
        assert_eq!(
            __private::reply(ok),
            Ok(lattice_state::encode(&5u16).unwrap())
        );
        let err: Result<u16, Oops> = Err(Oops::NoShell);
        assert_eq!(
            __private::reply(err).map_err(|e| e.code().to_owned()),
            Err("no_shell".to_owned())
        );
        let bad = __private::decode_action::<Oops>(&[9]);
        assert_eq!(bad, Err(AppError::platform(BAD_ACTION)));
    }

    /// Echoes the action back as the reply.
    struct Mirror;

    impl crate::Caller for Mirror {
        fn call(&self, action: Vec<u8>) -> crate::RawTicket {
            crate::RawTicket::ready(Ok(action))
        }
    }

    #[test]
    fn call_encodes_the_action_and_types_the_ticket() {
        let mut ticket = __private::call::<_, _, Oops, Oops>(&Mirror, &Oops::TooBig(4));
        assert_eq!(ticket.try_take(), Some(Ok(Oops::TooBig(4))));
    }
}
